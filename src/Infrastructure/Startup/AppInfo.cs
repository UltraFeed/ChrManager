using System.Reflection;
using ChrManager.Application;

namespace ChrManager.Infrastructure.Startup;

/// <summary>Static application metadata; the version comes from the assembly itself.</summary>
internal static class AppInfo
{
	private static readonly Assembly Assembly = typeof(AppInfo).Assembly;
	private static readonly AssemblyName Identity = Assembly.GetName();
	public static string Name { get; } = Identity.Name ?? throw new AppFailure(FailureKind.InvalidApplicationMetadata);
	public static string AssemblyVersion { get; } = Identity.Version?.ToString() ?? throw new AppFailure(FailureKind.InvalidApplicationMetadata);
	public static string UserAgent => $"{Name}/{AssemblyVersion}";
	public static string ExecutableName => Name + ".exe";
	public static string TemporaryPrefix => Name + "-";
	public static string IniMarker => "; Generated by " + Name + ".";
	public static string IniHeader => IniMarker + " Edit settings.json instead.\r\n";
	public static string Version { get; } = ReadVersion();
	public static string FullVersion => $"{Name} {Version}";

	private static string ReadVersion ()
	{
		string? informational = Assembly.GetCustomAttribute<AssemblyInformationalVersionAttribute>()?.InformationalVersion;
		if (string.IsNullOrEmpty(informational))
		{
			throw new AppFailure(FailureKind.InvalidApplicationMetadata);
		}

		int metadata = informational.IndexOf('+', StringComparison.Ordinal);
		string version = metadata > 0 ? informational [..metadata] : informational;
		if (!System.Version.TryParse(version, out _))
		{
			throw new AppFailure(FailureKind.InvalidApplicationMetadata);
		}

		return version;
	}
}
